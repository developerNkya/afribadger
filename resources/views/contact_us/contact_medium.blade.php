        .then((response) => response.json())
        .then((data) => {
          if (data.status === "success") {
            toastr.success(data.message);
            contactForm.reset();
          } else if (data.errors) {
            Object.values(data.errors).forEach((errorMsg) => toastr.error(errorMsg[0]));
